// Emit components.css from audit/redesign-brief.json.
//
// The brief is the output of a 10-agent pass that read the actual built markup
// and the original CSS for every class family. Generating the selector lists
// from it — rather than hand-guessing them — means each treatment is traceable
// to a component that really exists, and the structural warnings it returned
// are honoured instead of rediscovered by breaking something.
import fs from 'node:fs';
import path from 'node:path';

const ROOT = process.cwd();
const brief = JSON.parse(fs.readFileSync(path.join(ROOT, 'audit', 'redesign-brief.json'), 'utf8'));

// Structural warnings from the mapping, applied as exclusions.
// "\.dc-pill, .dc-visit__row, .bw-manifesto__value are hairline rows, never cards"
// "Keep .ethc-house bare (no pill bg/border/shadow)" · ".ha-nap non-glass"
const NEVER_GLASS = new Set(['.dc-pill', '.dc-visit__row', '.bw-manifesto__value', '.ethc-house', '.ha-nap']);

// The brief's glass list came from reading markup and missed real cards such as
// .et-svc (the six home service cards), which then rendered with no surface at
// all. audit/original-cards.json is the evidence-based complement: every class
// the ORIGINAL stylesheet gave a background AND a radius/shadow — i.e. every
// element that was a surface in the design being replaced. Union the two, then
// subtract the things that are surfaces but not CARDS.
const derived = JSON.parse(fs.readFileSync(path.join(ROOT, 'audit', 'original-cards.json'), 'utf8'));
const NOT_A_CARD = [
  /__(ic|ico|ring|mk|pin|dot|tag|arrow|go|by|k)$/,      // icon chips and badges
  /__(media|frame|portrait|photo|map)$/,                 // media frames
  /^\.(dot|u-dot|dotmark|ck|brand-mark|et-avatar|drawer|ecard|ecard-ico)$/,
  /^\.(dc-frame|et-frame|ha-media|ia-media|od-media|ethc-media|ethc-local__map|fu-map__frame|ct-map__frame)$/,
  /^\.(et-pill|et-dot|ethc-menu__chip|tib-chip|ethc-point|tib-point|ethc-plan|ct-find__tag|et-eyebrow)$/,
  /^\.rw-sec$/,                                          // NEVER make the section a card
  /^\.dc-darkedge$/,
];
const derivedCards = derived.filter((c) => !NOT_A_CARD.some((re) => re.test(c)));

const uniq = (a) => [...new Set(a)];
const clean = (list) => uniq((list || []).filter((s) => typeof s === 'string' && /^\.[a-zA-Z][\w-]*$/.test(s)));
const sel = (list) => clean(list).join(',\n');

const glass = uniq(clean(brief.glassSurfaces).concat(derivedCards)).filter((s) => !NEVER_GLASS.has(s));
const frames = clean(brief.mediaFrames);
const ctas = clean(brief.ctaButtons);
const pills = clean(brief.pills);
const rows = uniq(clean(brief.listRows).concat(['.dc-pill', '.dc-visit__row', '.bw-manifesto__value']));
const faq = clean(brief.accordions);
const stats = clean(brief.stats);
const eyebrows = clean(brief.eyebrows);
const onDark = clean(brief.onDarkSelectors);

// A media frame paints on the RIM only — the image inside is full-bleed cover.
const frameRims = frames.filter((s) => !/__img$|-img$|__scene$/.test(s));
const frameImgs = frames.filter((s) => /__img$|-img$|__scene$/.test(s));

const out = `/* =============================================================================
   AURORA GLASS — component treatments
   GENERATED by tools/build-components-css.mjs from audit/redesign-brief.json.
   Do not hand-edit: change the brief or the generator and re-run.

   Source of the selector lists: a 10-agent pass over the built markup and the
   original CSS, one agent per class family, ${'' + (brief.glassSurfaces || []).length} glass surfaces identified.

   Structural constraints honoured (from the mapping's own warnings):
     · .dc-pill / .dc-visit__row / .bw-manifesto__value are hairline ROWS, not cards
     · .ethc-house stays bare; .ha-nap is not glass
     · media frames paint on the RIM only — inner images stay full-bleed cover
     · nothing here sets position/display, so display:contents and absolutely
       positioned inset media keep working
   ========================================================================== */

/* ---------------------------------------------------- GLASS SURFACES (${glass.length}) */
${sel(glass)} {
  position: relative;
  background: var(--glass-bg);
  -webkit-backdrop-filter: var(--glass-blur);
  backdrop-filter: var(--glass-blur);
  border: 1px solid var(--glass-brd);
  border-radius: var(--r-lg);
  box-shadow: var(--glass-shadow), var(--glass-edge);
  transition: transform var(--t-mid) var(--ease),
              box-shadow var(--t-mid) var(--ease),
              border-color var(--t-mid) var(--ease),
              background-color var(--t-mid) var(--ease);
}

/* pointer-tracked specular highlight */
${clean(glass).map((s) => s + '::after').join(',\n')} {
  content: "";
  position: absolute;
  inset: 0;
  border-radius: inherit;
  pointer-events: none;
  opacity: 0;
  transition: opacity var(--t-mid) var(--ease);
  background: radial-gradient(20rem 20rem at var(--mx, 50%) var(--my, 0%), rgba(255,255,255,.5), transparent 60%);
}
${clean(glass).map((s) => s + ':hover::after').join(',\n')} { opacity: 1; }

${clean(glass).map((s) => s + ':hover').join(',\n')} {
  transform: translateY(-6px);
  box-shadow: var(--glass-lift), var(--glass-edge);
  border-color: rgba(22,179,147,.45);
  background: var(--glass-bg-2);
}

/* dark-band variants */
${clean(glass).map((s) => '.surface-dark ' + s).join(',\n')} {
  background: var(--glassd-bg);
  border-color: var(--glassd-brd);
  box-shadow: 0 24px 56px -26px rgba(0,0,0,.6), var(--glassd-edge);
}
${clean(glass).map((s) => '.surface-dark ' + s + ':hover').join(',\n')} {
  border-color: rgba(22,179,147,.55);
  background: rgba(12,40,44,.68);
}

/* ------------------------------------------------------ MEDIA FRAMES (${frameRims.length}) */
${sel(frameRims)} {
  border-radius: var(--r-xl);
  overflow: hidden;
  border: 1px solid var(--glass-brd);
  box-shadow: var(--glass-shadow);
  isolation: isolate;
}
${clean(frameRims).map((s) => s + '::after').join(',\n')} {
  content: "";
  position: absolute;
  inset: 0;
  border-radius: inherit;
  pointer-events: none;
  box-shadow: inset 0 0 0 1px rgba(255,255,255,.5),
              inset 0 -70px 90px -70px rgba(7,23,26,.55);
  transition: box-shadow var(--t-mid) var(--ease);
}
${clean(frameRims).map((s) => s + ':hover::after').join(',\n')} {
  box-shadow: inset 0 0 0 1px rgba(22,179,147,.55),
              inset 0 -70px 90px -70px rgba(7,23,26,.35);
}
/* inner images: full-bleed cover, slow zoom. Position is layout.css's job. */
${sel(frameImgs)},
${clean(frameRims).map((s) => s + ' img').join(',\n')} {
  transition: transform 1.1s var(--ease), filter var(--t-slow) var(--ease);
  will-change: transform;
}
${clean(frameRims).map((s) => s + ':hover img').join(',\n')} { transform: scale(1.055); }

/* ------------------------------------------------------- CTA / GO LINKS (${ctas.length}) */
${sel(ctas)} {
  display: inline-flex;
  align-items: center;
  gap: 8px;
  font-weight: 620;
  font-size: 15px;
  color: var(--g-teal);
  transition: color var(--t-mid) var(--ease), gap var(--t-mid) var(--ease);
}
${clean(ctas).map((s) => s + ':hover').join(',\n')} { color: var(--g-teal-deep); gap: 12px; }
${clean(ctas).map((s) => s + ' svg').join(',\n')} { transition: transform var(--t-mid) var(--ease); }
${clean(ctas).map((s) => s + ':hover svg').join(',\n')} { transform: translateX(4px); }
${clean(ctas).map((s) => '.surface-dark ' + s).join(',\n')} { color: var(--g-gold-lit); }
${clean(ctas).map((s) => '.surface-dark ' + s + ':hover').join(',\n')} { color: #fff; }

/* --------------------------------------------------------- PILLS / CHIPS (${pills.length}) */
${sel(pills)} {
  display: inline-flex;
  align-items: center;
  gap: 9px;
  padding: 9px 16px;
  font-size: 13.5px;
  font-weight: 600;
  color: var(--g-teal-deep);
  background: rgba(255,255,255,.6);
  -webkit-backdrop-filter: blur(12px) saturate(160%);
  backdrop-filter: blur(12px) saturate(160%);
  border: 1px solid rgba(11,115,96,.18);
  border-radius: var(--r-pill);
  box-shadow: inset 0 1px 0 rgba(255,255,255,.85);
  transition: transform var(--t-fast) var(--ease),
              border-color var(--t-mid) var(--ease),
              background-color var(--t-mid) var(--ease);
}
${clean(pills).map((s) => s + ':hover').join(',\n')} {
  transform: translateY(-2px);
  border-color: rgba(22,179,147,.5);
  background: rgba(255,255,255,.84);
}
${clean(pills).map((s) => s + ' svg').join(',\n')} { width: 17px; height: 17px; flex: none; color: var(--g-teal); }
${clean(pills).map((s) => '.surface-dark ' + s).join(',\n')} {
  color: var(--g-on-dark);
  background: rgba(255,255,255,.09);
  border-color: rgba(255,255,255,.18);
  box-shadow: inset 0 1px 0 rgba(255,255,255,.14);
}
${clean(pills).map((s) => '.surface-dark ' + s + ' svg').join(',\n')} { color: var(--g-gold-lit); }

/* -------------------------------------------------------- HAIRLINE ROWS (${rows.length}) */
${sel(rows)} {
  border-bottom: 1px solid rgba(15,34,38,.09);
  transition: padding-inline-start var(--t-mid) var(--ease),
              border-color var(--t-mid) var(--ease),
              background-color var(--t-mid) var(--ease);
}
${clean(rows).map((s) => s + ':hover').join(',\n')} {
  padding-inline-start: 8px;
  border-color: rgba(22,179,147,.42);
}
${clean(rows).map((s) => '.surface-dark ' + s).join(',\n')} { border-color: rgba(255,255,255,.10); }

/* ----------------------------------------------------------- ACCORDIONS (${faq.length}) */
${sel(faq)} {
  background: var(--glass-bg);
  -webkit-backdrop-filter: var(--glass-blur);
  backdrop-filter: var(--glass-blur);
  border: 1px solid var(--glass-brd);
  border-radius: var(--r-lg);
  box-shadow: var(--glass-edge);
  transition: box-shadow var(--t-mid) var(--ease), border-color var(--t-mid) var(--ease);
}
${clean(faq).map((s) => s + ':hover').join(',\n')} {
  border-color: rgba(22,179,147,.4);
  box-shadow: var(--glass-shadow), var(--glass-edge);
}

/* ---------------------------------------------------------------- STATS (${stats.length}) */
${sel(stats)} {
  font-variant-numeric: tabular-nums;
}
${clean(stats).filter((s) => /__k$|__year$/.test(s)).map((s) => s).join(',\n') || '.__no_stat_k'} {
  font-family: 'Space Grotesk', system-ui, sans-serif;
  font-size: clamp(30px, 3.6vw, 46px);
  font-weight: 700;
  line-height: 1;
  letter-spacing: -.035em;
  background: var(--grad-text);
  -webkit-background-clip: text;
  background-clip: text;
  -webkit-text-fill-color: transparent;
  color: transparent;
}

/* -------------------------------------------------------------- EYEBROWS (${eyebrows.length}) */
${sel(eyebrows)} {
  font-family: 'Space Mono', ui-monospace, monospace;
  font-size: 11.5px;
  font-weight: 700;
  letter-spacing: .2em;
  text-transform: uppercase;
  color: var(--g-teal);
}
${clean(eyebrows).map((s) => '.surface-dark ' + s).join(',\n')} { color: var(--g-gold-lit); }

/* ------------------------------------------------- ON-DARK TEXT COLOUR (${onDark.length}) */
${clean(onDark).map((s) => '.surface-dark ' + s).join(',\n')} {
  color: var(--g-on-dark);
}
`;

fs.mkdirSync(path.join(ROOT, 'src', 'styles'), { recursive: true });
fs.writeFileSync(path.join(ROOT, 'src', 'styles', 'components.css'), out);

console.log('components.css generated');
console.log('  glass surfaces ' + glass.length);
console.log('  media frames   ' + frameRims.length + ' rims + ' + frameImgs.length + ' inner images');
console.log('  cta links      ' + ctas.length);
console.log('  pills          ' + pills.length);
console.log('  hairline rows  ' + rows.length);
console.log('  accordions     ' + faq.length);
console.log('  stats          ' + stats.length);
console.log('  eyebrows       ' + eyebrows.length);
console.log('  on-dark        ' + onDark.length);
console.log('  excluded from glass by structural warning: ' + [...NEVER_GLASS].join(' '));
console.log('  bytes          ' + out.length);
